/**
 * Calendar strings are generated by Material/Android, not user-entered data.
 * Some Android versions ignore the numbering extension for date skeletons.
 */
@OptIn(ExperimentalMaterial3Api::class)
private fun latinCalendarFormatter(): DatePickerFormatter {
    val delegate = DatePickerDefaults.dateFormatter()
    fun String.latinDigits(): String = map { c ->
        if (c in '০'..'৯') '0' + (c - '০') else c
    }.joinToString("")
    return object : DatePickerFormatter {
        override fun formatMonthYear(monthMillis: Long?, locale: Locale): String? =
            delegate.formatMonthYear(monthMillis, locale)?.latinDigits()
        override fun formatDate(dateMillis: Long?, locale: Locale, forContentDescription: Boolean): String? =
            delegate.formatDate(dateMillis, locale, forContentDescription)?.latinDigits()
    }
}

/** Uses the app language and Latin digits; epoch-day storage still uses UTC midnight. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AppDatePickerDialog(initialDate: Long, onDismiss: () -> Unit, onDateSelected: (Long) -> Unit) {
    // Do not put the numbering extension on the Android resource Configuration:
    // Android 7 can then select English resources. It is safe on the picker model.
    val calendarLocale = AppLocale.calendarLocale(LocalConfiguration.current.locales[0])
    val yearRange = Dates.FIRST_PICKER_YEAR..Dates.LAST_PICKER_YEAR
    val saver = remember(calendarLocale) {
        listSaver<DatePickerState, Long>(
            save = { listOf(it.selectedDateMillis ?: Long.MIN_VALUE, it.displayedMonthMillis) },
            restore = {
                DatePickerState(
                    locale = calendarLocale,
                    initialSelectedDateMillis = it[0].takeUnless { value -> value == Long.MIN_VALUE },
                    initialDisplayedMonthMillis = it[1],
                    yearRange = yearRange
                )
            }
        )
    }
    val pickerState = rememberSaveable(calendarLocale.toLanguageTag(), initialDate, saver = saver) {
        DatePickerState(
            locale = calendarLocale,
            initialSelectedDateMillis = Dates.toPickerMillis(initialDate),
            yearRange = yearRange
        )
    }
    // Material's date picker and DatePickerDialog both require 360dp. Use a
    // Dialog whose entire surface is measured at compact density on narrow
    // phones; changing density only inside DatePickerDialog leaves its surface
    // at 360dp and clips both sides. Keep the user's font scale for text.
    val density = LocalDensity.current
    val screenWidth = LocalConfiguration.current.screenWidthDp
    val scale = ((screenWidth - 16f) / 360f).coerceIn(0.50f, 1f)
    val compactDensity = remember(density, scale) {
        Density(density.density * scale, density.fontScale / scale)
    }
    val title = stringResource(R.string.choose_date)
    Dialog(onDismissRequest = onDismiss, properties = DialogProperties(usePlatformDefaultWidth = false)) {
        CompositionLocalProvider(LocalDensity provides compactDensity) {
            // Bengali abbreviated weekdays can be longer than a cell. A slightly
            // smaller base size leaves room while still following system font scale.
            val typography = MaterialTheme.typography
            val calendarTypography = if (calendarLocale.language == "bn" && scale < 1f) {
                typography.copy(bodyLarge = typography.bodyLarge.copy(fontSize = 14.sp))
            } else typography
            MaterialTheme(typography = calendarTypography) {
                val colors = DatePickerDefaults.colors()
                Surface(
                    modifier = Modifier.width(360.dp).testTag("calendar_dialog").semantics { paneTitle = title },
                    shape = DatePickerDefaults.shape,
                    color = colors.containerColor,
                    tonalElevation = DatePickerDefaults.TonalElevation
                ) {
                    Column {
                        // On short or landscape screens the calendar can scroll,
                        // while its confirm and cancel buttons stay visible.
                        Box(Modifier.weight(1f, fill = false).verticalScroll(rememberScrollState())) {
                            DatePicker(
                                state = pickerState,
                                dateFormatter = remember { latinCalendarFormatter() },
                                showModeToggle = false,
                                colors = colors,
                                title = {
                                    Text(title, modifier = Modifier.padding(start = 24.dp, top = 16.dp),
                                        style = MaterialTheme.typography.labelLarge)
                                },
                                headline = {
                                    val selected = pickerState.selectedDateMillis?.let { Dates.fromPickerMillis(it) } ?: initialDate
                                    Text(stringResource(R.string.selected_date, Dates.display(selected)),
                                        modifier = Modifier.padding(start = 24.dp, end = 24.dp, top = 8.dp, bottom = 12.dp),
                                        style = MaterialTheme.typography.headlineSmall)
                                }
                            )
                        }
                        Row(
                            modifier = Modifier.fillMaxWidth().padding(end = 6.dp, bottom = 8.dp),
                            horizontalArrangement = Arrangement.End
                        ) {
                            TextButton(onClick = onDismiss) { Text(stringResource(R.string.cancel)) }
                            TextButton(
                                onClick = { pickerState.selectedDateMillis?.let { onDateSelected(Dates.fromPickerMillis(it)) } },
                                enabled = pickerState.selectedDateMillis != null
                            ) { Text(stringResource(R.string.ok)) }
                        }
                    }
                }
            }
        }
    }
}

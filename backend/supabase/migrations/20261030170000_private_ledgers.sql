-- ============================================================================
-- Private cloud ledgers: people, loans and cash.
--
-- Mirrors the existing Android Room schema (integer paisa, epoch-day dates,
-- epoch-millisecond createdAt, symmetric cash/loan links) so migration can copy
-- records without reformatting money or dates.
--
-- Privacy rule enforced here: every row belongs to exactly one account, and RLS
-- is owner-only. There is deliberately NO admin/super-admin read policy, so even
-- the SuperAdmin cannot read another account's ledger. A row's owner is taken
-- from the caller's token, never from the request body.
-- ============================================================================

create type public.person_type as enum ('lent', 'borrowed');

comment on type public.person_type is
  'Mirrors the app PersonType enum: LENT (money lent out) / BORROWED.';

-- --------------------------------------------------------------- helpers ----
create function private.touch_row_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

-- Ownership can never be re-pointed at another account.
create function private.guard_ledger_owner()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.owner_id is distinct from old.owner_id then
        raise exception 'a ledger row cannot change owner' using errcode = '42501';
    end if;
    if new.client_id is distinct from old.client_id then
        raise exception 'a ledger row cannot change its client id' using errcode = '42501';
    end if;
    return new;
end;
$$;

revoke all on function private.touch_row_updated_at() from public, anon, authenticated;
revoke all on function private.guard_ledger_owner() from public, anon, authenticated;

-- ---------------------------------------------------------------- people ----
create table public.people (
    id uuid primary key default gen_random_uuid(),
    owner_id uuid not null default auth.uid()
        references auth.users (id) on delete cascade,
    client_id uuid not null default gen_random_uuid(),
    name text not null,
    phone text not null default '',
    note text not null default '',
    type public.person_type not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    deleted_at timestamptz,
    constraint people_name_check check (
        char_length(name) between 1 and 120
        and name = btrim(name)
        and name !~ '[[:cntrl:]]'
    ),
    constraint people_phone_check check (char_length(phone) <= 40),
    constraint people_note_check check (char_length(note) <= 2000),
    constraint people_client_id_unique unique (owner_id, client_id)
);

comment on table public.people is
  'A person in one account''s ledger. Owner-only via RLS; no admin access.';
comment on column public.people.client_id is
  'Stable id generated by the app so retried uploads cannot duplicate a person.';

create index people_owner_idx on public.people (owner_id, deleted_at);
create index people_owner_type_name_idx on public.people (owner_id, type, name);

create trigger people_touch_updated_at
    before update on public.people
    for each row execute function private.touch_row_updated_at();

create trigger people_guard_owner
    before update on public.people
    for each row execute function private.guard_ledger_owner();

alter table public.people enable row level security;

create policy people_select_own on public.people
    for select to authenticated
    using (owner_id = auth.uid() and private.is_active());

create policy people_insert_own on public.people
    for insert to authenticated
    with check (owner_id = auth.uid() and private.is_active());

create policy people_update_own on public.people
    for update to authenticated
    using (owner_id = auth.uid() and private.is_active())
    with check (owner_id = auth.uid() and private.is_active());

create policy people_delete_own on public.people
    for delete to authenticated
    using (owner_id = auth.uid() and private.is_active());

revoke all on public.people from anon, authenticated;
grant select, insert, update, delete on public.people to authenticated;

-- ----------------------------------------------------------- loan entries ---
create table public.loan_entries (
    id uuid primary key default gen_random_uuid(),
    owner_id uuid not null default auth.uid()
        references auth.users (id) on delete cascade,
    client_id uuid not null default gen_random_uuid(),
    person_id uuid not null references public.people (id) on delete cascade,
    entry_date bigint not null,
    loan bigint not null default 0,
    paid bigint not null default 0,
    description text not null default '',
    created_at_ms bigint not null,
    linked_cash_entry_id uuid,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    deleted_at timestamptz,
    constraint loan_entries_amounts_check check (loan >= 0 and paid >= 0),
    constraint loan_entries_not_empty_check check (loan > 0 or paid > 0),
    constraint loan_entries_date_check check (entry_date between -719162 and 2932896),
    constraint loan_entries_created_check check (created_at_ms > 0),
    constraint loan_entries_description_check check (char_length(description) <= 2000),
    constraint loan_entries_client_id_unique unique (owner_id, client_id)
);


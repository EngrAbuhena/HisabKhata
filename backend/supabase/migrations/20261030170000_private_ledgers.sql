-- ------------------------------------------------- cross-links (deferred) ---
-- The two ledgers point at each other. Foreign keys are added after both tables
-- exist and are deferred so one transaction can insert and link both rows.
alter table public.loan_entries
    add constraint loan_entries_linked_cash_fk
    foreign key (linked_cash_entry_id) references public.cash_entries (id)
    on delete set null deferrable initially deferred;

alter table public.cash_entries
    add constraint cash_entries_linked_loan_fk
    foreign key (linked_loan_entry_id) references public.loan_entries (id)
    on delete set null deferrable initially deferred;

-- Symmetry and same-owner are checked at commit, matching BackupCodec.validate.
create function private.enforce_link_symmetry()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_other uuid;
    v_owner uuid;
    v_self uuid;
begin
    if tg_op = 'DELETE' then
        -- The opposite row has its pointer nulled by ON DELETE SET NULL.
        return null;
    end if;

    if tg_table_name = 'loan_entries' then
        v_other := new.linked_cash_entry_id;
        v_owner := new.owner_id;
        v_self := new.id;
        if v_other is null then return null; end if;
        if not exists (
            select 1 from public.cash_entries c
             where c.id = v_other
               and c.owner_id = v_owner
               and c.linked_loan_entry_id = v_self
        ) then
            raise exception 'loan/cash link must be symmetric and same-owner'
                using errcode = '23514';
        end if;
    else
        v_other := new.linked_loan_entry_id;
        v_owner := new.owner_id;
        v_self := new.id;
        if v_other is null then return null; end if;
        if not exists (
            select 1 from public.loan_entries l
             where l.id = v_other
               and l.owner_id = v_owner
               and l.linked_cash_entry_id = v_self
        ) then
            raise exception 'cash/loan link must be symmetric and same-owner'
                using errcode = '23514';
        end if;
    end if;

    return null;
end;
$$;

revoke all on function private.enforce_link_symmetry() from public, anon, authenticated;

create constraint trigger loan_entries_link_symmetry
    after insert or update on public.loan_entries
    deferrable initially deferred
    for each row execute function private.enforce_link_symmetry();

create constraint trigger cash_entries_link_symmetry
    after insert or update on public.cash_entries
    deferrable initially deferred
    for each row execute function private.enforce_link_symmetry();

